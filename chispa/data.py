"""Datos de CHISPA-lab: descarga de codeparrot-clean, reagrupado por repositorio, partición y flujo de tokens.

Uso:
  python -m chispa.data descargar  --out DATOS [--max-shards N]
  python -m chispa.data parcial    --out DATOS --mb 30          # prueba local: primeros MB de un fragmento
  python -m chispa.data agrupar    --datos DATOS                # -> DATOS/repos/{train,heldout}-*.jsonl.gz
  python -m chispa.data tokenizador --datos DATOS [--chars 50e6]
  python -m chispa.data base       --datos DATOS --tokens 5e8 --seed 1337   # -> DATOS/tok/base-*.bin (uint16)
"""
from __future__ import annotations

import argparse, glob, gzip, hashlib, io, json, os, random, sys, zlib
from pathlib import Path

import numpy as np

REPO_ID = "codeparrot/codeparrot-clean"
PERMISIVAS = {"mit", "apache-2.0", "bsd-2-clause", "bsd-3-clause", "isc", "unlicense"}
N_BUCKETS = 64


def es_retenido(repo: str) -> bool:
    return int(hashlib.sha1(repo.encode()).hexdigest(), 16) % 100 < 3


def bucket(repo: str) -> int:
    return int(hashlib.md5(repo.encode()).hexdigest(), 16) % N_BUCKETS


# ---------------------------------------------------------------- descarga
def descargar(out: Path, max_shards: int | None):
    from huggingface_hub import HfApi, hf_hub_download
    files = sorted(f for f in HfApi().list_repo_files(REPO_ID, repo_type="dataset") if f.endswith(".json.gz"))
    if max_shards:
        files = files[:max_shards]
    raw = out / "raw"; raw.mkdir(parents=True, exist_ok=True)
    for i, f in enumerate(files, 1):
        p = hf_hub_download(REPO_ID, f, repo_type="dataset", local_dir=raw)
        print(f"[{i}/{len(files)}] {p}", flush=True)


def parcial(out: Path, mb: int):
    import urllib.request
    raw = out / "raw"; raw.mkdir(parents=True, exist_ok=True)
    url = f"https://huggingface.co/datasets/{REPO_ID}/resolve/main/file-000000000001.json.gz"
    req = urllib.request.Request(url, headers={"Range": f"bytes=0-{mb * 1_000_000}"})
    data = urllib.request.urlopen(req).read()
    d = zlib.decompressobj(16 + zlib.MAX_WBITS)
    txt = d.decompress(data).decode("utf-8", "ignore")
    lines = txt.split("\n")[:-1]  # la última puede estar cortada
    with gzip.open(raw / "parcial.json.gz", "wt", encoding="utf-8") as f:
        for l in lines:
            f.write(l + "\n")
    print(f"parcial: {len(lines)} registros", flush=True)


# ---------------------------------------------------------------- agrupar
def _registros(raw: Path):
    for p in sorted(raw.glob("*.json.gz")):
        with gzip.open(p, "rt", encoding="utf-8", errors="ignore") as f:
            for l in f:
                try:
                    r = json.loads(l)
                except json.JSONDecodeError:
                    continue
                yield r


def _mapa(args):
    """Un fragmento crudo -> 64 archivos de cubeta propios (sin escrituras compartidas entre procesos)."""
    p, tmp, k = args
    outs = [gzip.open(tmp / f"b{b:02d}_s{k:03d}.jsonl.gz", "wt", encoding="utf-8", compresslevel=1) for b in range(N_BUCKETS)]
    n = kept = 0
    with gzip.open(p, "rt", encoding="utf-8", errors="ignore") as f:
        for l in f:
            try:
                r = json.loads(l)
            except json.JSONDecodeError:
                continue
            n += 1
            if r.get("license") not in PERMISIVAS or r.get("autogenerated") in (True, "True"):
                continue
            kept += 1
            outs[bucket(r["repo_name"])].write(json.dumps(
                {"repo": r["repo_name"], "path": r["path"], "content": r["content"]}, ensure_ascii=False) + "\n")
    for o in outs:
        o.close()
    return n, kept


def _reduce(args):
    b, tmp, rep = args
    repos: dict[str, list] = {}
    parts = sorted(tmp.glob(f"b{b:02d}_s*.jsonl.gz"))
    for q in parts:
        with gzip.open(q, "rt", encoding="utf-8") as f:
            for l in f:
                r = json.loads(l)
                repos.setdefault(r["repo"], []).append({"path": r["path"], "content": r["content"]})
    st = {"train": [0, 0], "heldout": [0, 0]}
    with gzip.open(rep / f"train-{b:02d}.jsonl.gz", "wt", encoding="utf-8") as ft, \
         gzip.open(rep / f"heldout-{b:02d}.jsonl.gz", "wt", encoding="utf-8") as fh:
        for name in sorted(repos):
            files = sorted(repos[name], key=lambda x: x["path"])
            split = "heldout" if es_retenido(name) else "train"
            (fh if split == "heldout" else ft).write(json.dumps({"repo": name, "files": files}, ensure_ascii=False) + "\n")
            st[split][0] += 1; st[split][1] += len(files)
    for q in parts:
        q.unlink()
    return st


def agrupar(datos: Path, procs: int = 8, borrar_raw: bool = False):
    from multiprocessing import Pool
    tmp = datos / "buckets"; tmp.mkdir(parents=True, exist_ok=True)
    rep = datos / "repos"; rep.mkdir(exist_ok=True)
    raws = sorted((datos / "raw").glob("*.json.gz"))
    with Pool(procs) as pool:
        res = pool.map(_mapa, [(p, tmp, k) for k, p in enumerate(raws)])
        print(f"registros {sum(r[0] for r in res)}, permisivos {sum(r[1] for r in res)}", flush=True)
        if borrar_raw:
            for p in raws:
                p.unlink()
        sts = pool.map(_reduce, [(b, tmp, rep) for b in range(N_BUCKETS)])
    stats = {"train": [sum(s["train"][0] for s in sts), sum(s["train"][1] for s in sts)],
             "heldout": [sum(s["heldout"][0] for s in sts), sum(s["heldout"][1] for s in sts)]}
    json.dump(stats, open(rep / "stats.json", "w"))
    print("repos/archivos:", stats, flush=True)


def repos(datos: Path, split: str):
    for p in sorted((datos / "repos").glob(f"{split}-*.jsonl.gz")):
        with gzip.open(p, "rt", encoding="utf-8") as f:
            for l in f:
                yield json.loads(l)


# ---------------------------------------------------------------- FIM
def fim(text: str, rng: random.Random, p_fim=0.5, p_linea=0.5) -> tuple[str, bool]:
    """Devuelve el documento transformado (PSM) o el original. La mitad de los FIM son de resto de línea."""
    if rng.random() >= p_fim or len(text) < 20:
        return text, False
    if rng.random() < p_linea:
        starts = [0] + [i + 1 for i, c in enumerate(text) if c == "\n"]
        ls = rng.choice(starts)
        le = text.find("\n", ls); le = len(text) if le < 0 else le
        line = text[ls:le]
        ind = len(line) - len(line.lstrip())
        if le - (ls + ind) < 2:
            return text, False
        a = rng.randint(ls + ind, le - 1); b = le
    else:
        a, b = sorted(rng.sample(range(len(text) + 1), 2))
    pre, mid, suf = text[:a], text[a:b], text[b:]
    return f"<fim_prefix>{pre}<fim_suffix>{suf}<fim_middle>{mid}", True


def base(datos: Path, tokens: float, seed: int, shard_tokens: int = 50_000_000):
    from .tok import cargar
    tk = cargar(datos)
    eot = tk.token_to_id("<|endoftext|>")
    rng = random.Random(seed)
    out = datos / "tok"; out.mkdir(exist_ok=True)
    buf, total, k, nfim, ndoc = [], 0, 0, 0, 0
    batch = []

    def flush_batch():
        nonlocal total, nfim
        enc = tk.encode_batch([t for t, _ in batch], add_special_tokens=False)
        for e in enc:
            buf.extend(e.ids); buf.append(eot)
        total += sum(len(e.ids) + 1 for e in enc)
        batch.clear()

    def flush_shard(final=False):
        nonlocal k, buf
        while len(buf) >= shard_tokens or (final and buf):
            arr = np.array(buf[:shard_tokens], dtype=np.uint16)
            arr.tofile(out / f"base-{k:03d}.bin"); k += 1
            buf = buf[shard_tokens:]

    for r in repos(datos, "train"):
        for f in r["files"]:
            t, isf = fim(f["content"], rng)
            nfim += isf; ndoc += 1
            batch.append((t, isf))
            if len(batch) >= 2000:
                flush_batch(); flush_shard()
                print(f"tokens {total/1e6:.1f}M docs {ndoc} fim {nfim}", flush=True)
            if total >= tokens:
                break
        if total >= tokens:
            break
    if batch:
        flush_batch()
    flush_shard(final=True)
    json.dump({"tokens": total, "docs": ndoc, "fim": nfim, "seed": seed, "shards": k}, open(out / "base.json", "w"))
    print(f"base: {total} tokens en {k} fragmentos", flush=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd")
    ap.add_argument("--out"); ap.add_argument("--datos")
    ap.add_argument("--max-shards", type=int); ap.add_argument("--mb", type=int, default=30)
    ap.add_argument("--chars", type=float, default=50e6)
    ap.add_argument("--tokens", type=float, default=5e8); ap.add_argument("--seed", type=int, default=1337)
    ap.add_argument("--procs", type=int, default=8); ap.add_argument("--borrar-raw", action="store_true")
    a = ap.parse_args()
    if a.cmd == "descargar":
        descargar(Path(a.out), a.max_shards)
    elif a.cmd == "parcial":
        parcial(Path(a.out), a.mb)
    elif a.cmd == "agrupar":
        agrupar(Path(a.datos), a.procs, a.borrar_raw)
    elif a.cmd == "tokenizador":
        from .tok import entrenar
        entrenar(Path(a.datos), int(a.chars))
    elif a.cmd == "base":
        base(Path(a.datos), a.tokens, a.seed)
    else:
        sys.exit(f"comando desconocido: {a.cmd}")


if __name__ == "__main__":
    main()
